-- Adds global teacher-key support to the Worker, matching the Node server.
-- TEACHER_KEYS stores the global teacher keys that may create instances and
-- view their own instances via the teacher portal. TEACHER_ACCESS_KEY records
-- which global teacher key owns each instance.
CREATE TABLE IF NOT EXISTS TEACHER_KEYS (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  TEACHER_KEY TEXT UNIQUE NOT NULL,
  LABEL TEXT,
  CREATED_AT TEXT DEFAULT CURRENT_TIMESTAMP NOT NULL
);

ALTER TABLE INSTANCES ADD COLUMN TEACHER_ACCESS_KEY TEXT;

CREATE INDEX IF NOT EXISTS IDX_INSTANCES_TEACHER_ACCESS_KEY ON INSTANCES (TEACHER_ACCESS_KEY);
CREATE UNIQUE INDEX IF NOT EXISTS IDX_TEACHER_KEYS_KEY_UNIQUE ON TEACHER_KEYS (TEACHER_KEY);
